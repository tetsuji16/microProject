package com.microproject.exchange;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Stream;

import org.junit.jupiter.api.Test;

import com.microproject.pm.task.Project;
import com.microproject.pm.task.ProjectFactory;
import com.microproject.util.SafeObjectInput;

/**
 * Records the {@code com.microproject.*} classes that appear in the Java serialization streams
 * of every checked-in {@code .mpo} / {@code .pod} fixture and compares them with
 * {@code testdata/persisted-classes.txt}. The list is the inventory of classes whose names are
 * part of the persisted wire contract; changing it means a persisted class was added, removed
 * or moved and the relocation/serialVersionUID handling must be reviewed.
 *
 * <p>Regenerate with
 * {@code .\gradlew.bat :microproject_exchange:test --tests "*PersistedClassInventoryTest" -Dmicroproject.updatePersistedClasses=true}.
 */
class PersistedClassInventoryTest {
	private static final String UPDATE_PROPERTY = "microproject.updatePersistedClasses";
	private static final String HEADER = "# generated by PersistedClassInventoryTest; regenerate with "
		+ ".\\gradlew.bat :microproject_exchange:test --tests \"*PersistedClassInventoryTest\" -D" + UPDATE_PROPERTY + "=true";

	@Test
	void persistedClassInventoryMatchesCheckedInList() throws Exception {
		List<Path> fixtures = fixtures();
		assertTrue(fixtures.size() >= 12, "expected the checked-in MPO/POD corpus but found " + fixtures);
		Set<String> observed = new TreeSet<>();
		for (Path fixture : fixtures) {
			try (AutoCloseable observation = SafeObjectInput.observeResolvedClasses(type -> {
				if (type.getName().startsWith("com.microproject.")) observed.add(type.getName());
			})) {
				readThroughProductionPath(fixture);
			}
		}
		Path inventory = inventoryFile();
		if (Boolean.getBoolean(UPDATE_PROPERTY)) {
			List<String> lines = new ArrayList<>();
			lines.add(HEADER);
			lines.addAll(observed);
			Files.writeString(inventory, String.join("\r\n", lines) + "\r\n", StandardCharsets.UTF_8);
		}
		assertTrue(Files.isRegularFile(inventory), "missing inventory " + inventory);
		Set<String> expected = new TreeSet<>();
		for (String line : Files.readAllLines(inventory, StandardCharsets.UTF_8)) {
			if (!line.isBlank() && !line.startsWith("#")) expected.add(line.trim());
		}
		assertEquals(expected, observed, "persisted class inventory changed; if intended regenerate with -D"
			+ UPDATE_PROPERTY + "=true");
	}

	private static void readThroughProductionPath(Path fixture) throws Exception {
		String name = fixture.getFileName().toString();
		FileImporter importer = name.endsWith(".mpo") ? new MpoFileImporter() : new LocalFileImporter();
		importer.setProjectFactory(ProjectFactory.getInstance());
		importer.setFileName(fixture.toAbsolutePath().toString());
		importer.importFile();
		Project project = importer.getProject();
		assertNotNull(project, "fixture did not load: " + fixture);
	}

	private static List<Path> fixtures() throws IOException {
		List<Path> result = new ArrayList<>();
		for (Path root : List.of(directory("testdata"), directory("samples"))) {
			try (Stream<Path> files = Files.walk(root)) {
				files.filter(Files::isRegularFile).filter(PersistedClassInventoryTest::isPersistedFixture)
					.sorted().forEach(result::add);
			}
		}
		return result;
	}

	private static boolean isPersistedFixture(Path path) {
		String name = path.getFileName().toString().toLowerCase(java.util.Locale.ROOT);
		return name.endsWith(".mpo") || name.endsWith(".pod");
	}

	/** Resolves {@code testdata} (module) or {@code samples} (repository root) from either working directory. */
	private static Path directory(String name) {
		List<String> candidates = name.equals("samples")
			? List.of("samples", "../../samples")
			: List.of("testdata", "modules/microproject_exchange/testdata");
		for (String candidate : candidates) {
			File dir = new File(candidate);
			if (dir.isDirectory()) return dir.toPath();
		}
		throw new AssertionError("Cannot locate " + name + " directory");
	}

	private static Path inventoryFile() {
		return directory("testdata").resolve("persisted-classes.txt");
	}
}
